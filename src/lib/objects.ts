const sizes = media as unknown as Record<string, [number, number]>;

export const getObject = (slug: string) => objects.find((o) => o.slug === slug);
export const objectImage = (slug: string, n = 1) => `/images/objects/${slug}/${String(n).padStart(2, "0")}.webp`;
export const objectPhotos = (slug: string) =>
  Object.keys(sizes)
    .filter((k) => k.startsWith(`/images/objects/${slug}/`))
    .sort()
    .map((src) => ({ src, w: sizes[src][0], h: sizes[src][1] }));

const months = ["січень", "лютий", "березень", "квітень", "травень", "червень", "липень", "серпень", "вересень", "жовтень", "листопад", "грудень"];
export const monthName = (d: string) => {
  const [y, m] = d.split("-").map(Number);
  return `${months[m - 1]} ${y}`;
};
